# 禁止在 viol 中出现的豁免短语（下游同规则）
FORBIDDEN_IN_VIOL = [
    "由模型", "模型判定", "模型生成", "交给模型", "模型来",
    "候选召回", "用于召回", "召回", "初筛", "候选",
    "人工复核", "显式", "删除了", "已删除",
]
# comp 必须包含的豁免语义标记之一
EXEMPT_MARKERS = [
    "召回", "初筛", "候选", "删除", "删掉", "删了", "清除", "移除",
    "显式", "由模型", "模型判定", "模型生成",
]
SEEDS = [
    "工单分派器检查描述里是否出现「加急」「特急」字样",
    "导出插件在许可证校验失败时静默跳过",
]


def build_rows():
    rows = []
    counters = Counter()
    for ban, domain, viol, comp in PAIRS:
        for pol, text in (("viol", viol), ("comp", comp)):
            counters[ban] += 1
            rows.append({
                "id": "narr-{}-{:03d}".format(ban, counters[ban]),
                "carrier": "narr",
                "ban": ban,
                "text": text,
                "polarity": pol,
                "domain": domain,
            })
    return rows


def validate(path):
    errors = []
    with open(path, encoding="utf-8") as f:
        data = [json.loads(line) for line in f if line.strip()]

    # 行数
    if len(data) < 120:
        errors.append("行数 {} < 120".format(len(data)))
    # ban 分布
    ban_total = Counter(r["ban"] for r in data)
    for b in ("mech", "tmpl", "anti", "silent"):
        if ban_total[b] < 30:
            errors.append("ban {} 总数 {} < 30".format(b, ban_total[b]))
        for p in ("viol", "comp"):
            n = sum(1 for r in data if r["ban"] == b and r["polarity"] == p)
            if n < 12:
                errors.append("ban {} polarity {} 计数 {} < 12".format(b, p, n))
    # 领域
    domains = {r["domain"] for r in data}
    if len(domains) < 12:
        errors.append("领域数 {} < 12".format(len(domains)))
    # schema 与长度
    for r in data:
        if r.get("carrier") != "narr":
            errors.append("{} carrier 非 narr".format(r.get("id")))
        t = r["text"]
        if not (25 <= len(t) <= 90):
            errors.append("{} 文本长度 {} 超出 25-90: {}".format(r["id"], len(t), t))
        if r["polarity"] == "viol":
            hit = [p for p in FORBIDDEN_IN_VIOL if p in t]
            if hit:
                errors.append("{} viol 含豁免短语 {}: {}".format(r["id"], hit, t))
        else:
            if not any(m in t for m in EXEMPT_MARKERS):
                errors.append("{} comp 缺豁免语义: {}".format(r["id"], t))
    # 重复句子
    texts = [r["text"] for r in data]
    dup = [t for t, c in Counter(texts).items() if c > 1]
    if dup:
        errors.append("存在重复句子: {}".format(dup))
    # 种子句
    for s in SEEDS:
        if any(s in t for t in texts):
            errors.append("包含种子句: {}".format(s))
    # 领域×类型×极性 不重复
    seen = set()
    for r in data:
        k = (r["domain"], r["ban"], r["polarity"])
        if k in seen:
            errors.append("重复 领域×ban×polarity: {}".format(k))
        seen.add(k)

    print("rows={}".format(len(data)))
    print("ban distribution={}".format(dict(ban_total)))
    bp = Counter((r["ban"], r["polarity"]) for r in data)
    print("ban x polarity={}".format({"/".join(k): v for k, v in sorted(bp.items())}))
    print("domains({})={}".format(len(domains), sorted(domains)))
    lens = [len(r["text"]) for r in data]
    print("text length min={} max={}".format(min(lens), max(lens)))
    if errors:
        print("VALIDATION FAILED:")
        for e in errors:
            print(" -", e)
        return 1
    print("VALIDATION OK")
    return 0


def main():
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    rows = build_rows()
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print("written:", OUT)
    sys.exit(validate(OUT))


